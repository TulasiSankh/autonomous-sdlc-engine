"""Architect and Project Scaffolder Agent module.

Provides greenfield project generation templates and technical architecture blueprints for:
- Full-stack React + FastAPI / Express applications
- Python API services (FastAPI, SQLite/SQLAlchemy, pytest)
- Node.js / TypeScript microservices
- CLI tools and automation engines

Ensures standard project layout, dependency files (requirements.txt, package.json),
safe configuration templates (.env.example), test setup, and automated README generation.
"""

from typing import Dict, List, Optional
from pydantic import BaseModel, Field

from agents.developer import ImplementationProposal, ProposedFileChange


class ProjectTemplate(BaseModel):
    """Specification of a project template archetype."""

    template_id: str = Field(..., description="Unique template identifier (e.g. 'fastapi_api', 'react_vite').")
    name: str = Field(..., description="Human-readable project template name.")
    description: str = Field(..., description="Overview of stack and capabilities.")
    tech_stack: List[str] = Field(..., description="Technologies and libraries included.")
    files: Dict[str, str] = Field(..., description="Relative file paths mapped to file contents.")


class ArchitectAgent:
    """Agent that designs project structure and generates turnkey application scaffolding."""

    def detect_greenfield_request(self, task_description: str) -> bool:
        """Determines whether a user prompt represents creating a new project from scratch."""
        desc = task_description.lower()
        greenfield_triggers = [
            "create a new project",
            "build a complete",
            "scaffold a new",
            "initialize project",
            "create a project",
            "build a new application",
            "start a new app",
            "build a student management system",
            "create a dashboard with charts",
        ]
        return any(trigger in desc for trigger in greenfield_triggers)

    def scaffold_project(
        self,
        project_name: str,
        template_type: str = "fastapi_sqlite",
        custom_instructions: Optional[str] = None,
    ) -> ImplementationProposal:
        """Generates complete scaffolding files for a new production-ready application.

        Args:
            project_name: Name of the application / root package.
            template_type: One of 'fastapi_sqlite', 'react_frontend', or 'fullstack'.
            custom_instructions: Optional user-specific requirements.

        Returns:
            ImplementationProposal populated with all required boilerplate and functional files.
        """
        files: Dict[str, str] = {}
        changes: List[ProposedFileChange] = []

        if template_type == "react_frontend":
            files = self._get_react_vite_template(project_name)
        elif template_type == "fullstack":
            files = {
                **self._get_fastapi_template(f"{project_name}_backend", prefix="backend/"),
                **self._get_react_vite_template(f"{project_name}_frontend", prefix="frontend/"),
            }
        else:
            files = self._get_fastapi_template(project_name)

        for path in files.keys():
            changes.append(
                ProposedFileChange(
                    path=path,
                    action="create",
                    description=f"Generated boilerplate and initial implementation for {path}",
                )
            )

        summary = f"Scaffolded new {template_type} project '{project_name}' with {len(files)} files."
        return ImplementationProposal(
            task_id=f"scaffold_{project_name}",
            task=f"Scaffold {template_type} project '{project_name}'",
            summary=summary,
            files_to_change=changes,
            diffs=[],
        )

    def _get_fastapi_template(self, app_name: str, prefix: str = "") -> Dict[str, str]:
        """Generates standard FastAPI + SQLite project files."""
        return {
            f"{prefix}README.md": f"# {app_name}\n\nAutomated application generated by Autonomous SDLC Engine.\n\n## Quickstart\n\n```bash\npip install -r requirements.txt\nuvicorn main:app --reload\n```\n",
            f"{prefix}requirements.txt": "fastapi>=0.115.0\nuvicorn>=0.30.0\npydantic>=2.7.0\npytest>=8.0.0\nhttpx>=0.27.0\n",
            f"{prefix}.env.example": "APP_ENV=development\nPORT=8000\nDATABASE_URL=sqlite:///./app.db\n",
            f"{prefix}main.py": (
                "from fastapi import FastAPI\n\n"
                f"app = FastAPI(title='{app_name}', version='1.0.0')\n\n"
                "@app.get('/health')\n"
                "def health():\n"
                "    return {'status': 'healthy', 'app': '" + app_name + "'}\n\n"
                "@app.get('/api/items')\n"
                "def list_items():\n"
                "    return {'items': []}\n"
            ),
            f"{prefix}tests/test_main.py": (
                "from fastapi.testclient import TestClient\n"
                "from main import app\n\n"
                "client = TestClient(app)\n\n"
                "def test_health():\n"
                "    res = client.get('/health')\n"
                "    assert res.status_code == 200\n"
                "    assert res.json()['status'] == 'healthy'\n"
            ),
        }

    def _get_react_vite_template(self, app_name: str, prefix: str = "") -> Dict[str, str]:
        """Generates standard React + Vite frontend files."""
        return {
            f"{prefix}package.json": (
                "{\n"
                f'  "name": "{app_name.lower().replace("_", "-")}",\n'
                '  "private": true,\n'
                '  "version": "0.1.0",\n'
                '  "type": "module",\n'
                '  "scripts": {\n'
                '    "dev": "vite",\n'
                '    "build": "vite build",\n'
                '    "test": "vitest run"\n'
                "  },\n"
                '  "dependencies": {\n'
                '    "react": "^19.0.0",\n'
                '    "react-dom": "^19.0.0"\n'
                "  }\n"
                "}\n"
            ),
            f"{prefix}README.md": f"# {app_name}\n\nFrontend application initialized by Autonomous SDLC Engine.\n\n```bash\nnpm install\nnpm run dev\n```\n",
            f"{prefix}src/App.tsx": (
                "import React from 'react';\n\n"
                f"export default function App() {{\n"
                f"  return (\n"
                f"    <div style={{ padding: '2rem', fontFamily: 'sans-serif' }}>\n"
                f"      <h1>{app_name}</h1>\n"
                f"      <p>Welcome to your new autonomous application.</p>\n"
                f"    </div>\n"
                f"  );\n"
                f"}}\n"
            ),
        }
